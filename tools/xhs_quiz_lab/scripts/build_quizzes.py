def build_quiz(blueprint_key: str, slug: str, title: str, subtitle: str) -> dict:
    blueprint = BLUEPRINTS[blueprint_key]
    questions = []
    for prompt_key, prompt_text in blueprint["prompts"]:
        options = []
        for result in blueprint["results"]:
            options.append(
                {
                    "text": result["answers"][prompt_key],
                    "resultKey": result["key"],
                    "weight": 1,
                }
            )
        questions.append(
            {
                "prompt": prompt_text,
                "options": options,
            }
        )

    results = []
    for result in blueprint["results"]:
        results.append(
            {
                "key": result["key"],
                "title": result["title"],
                "badge": result["badge"],
                "summary": result["summary"],
                "match": result["match"],
                "warning": result["warning"],
                "advice": result["advice"],
                "mantra": result["mantra"],
                "share": result["share"],
                "tags": result["tags"],
            }
        )

    return {
        "slug": slug,
        "title": title,
        "subtitle": subtitle,
        "category": blueprint["category"],
        "collection": blueprint["collection"],
        "shareAngle": blueprint["shareAngle"],
        "resultIntro": blueprint["resultIntro"],
        "palette": blueprint["palette"],
        "questions": questions,
        "results": results,
    }


def write_page(quiz: dict) -> None:
    target = PAGES_DIR / f"{quiz['slug']}.html"
    target.write_text(
        PAGE_TEMPLATE.format(title=quiz["title"], subtitle=quiz["subtitle"], slug=quiz["slug"]),
        encoding="utf-8",
    )


def main() -> None:
    quizzes = []
    for blueprint_key, items in TOPIC_GROUPS.items():
        for slug, title, subtitle in items:
            quizzes.append(build_quiz(blueprint_key, slug, title, subtitle))

    PAGES_DIR.mkdir(parents=True, exist_ok=True)
    for page in PAGES_DIR.glob("*.html"):
        page.unlink()

    for quiz in quizzes:
        write_page(quiz)

    payload = {
        "meta": {
            "generatedBy": "tools/xhs_quiz_lab/scripts/build_quizzes.py",
            "quizCount": len(quizzes),
            "questionCountPerQuiz": len(quizzes[0]["questions"]) if quizzes else 0,
        },
        "quizzes": quizzes,
    }

    DATA_JSON.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    DATA_JS.write_text(
        "window.quizCatalog = " + json.dumps(payload, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    INDEX_HTML.write_text(INDEX_TEMPLATE, encoding="utf-8")

    print(f"Generated {len(quizzes)} quizzes in {ROOT}")


if __name__ == "__main__":
    main()
